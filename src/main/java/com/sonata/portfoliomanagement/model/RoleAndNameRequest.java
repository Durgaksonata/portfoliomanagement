package com.sonata.portfoliomanagement.model;

public class RoleAndNameRequest {

    private String role;
    private String name;

    // Getters and setters
    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}